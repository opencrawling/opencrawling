package org.opencrawling.alfresco;

import java.io.IOException;

/**
 * Exception raised when an Alfresco Content Services REST API call fails with an unexpected HTTP status.
 * Extends {@link IOException} for backward compatibility with callers and discovery exception handling.
 */
public class AlfrescoApiException extends IOException {

    private final int statusCode;
    private final String responseBody;

    public AlfrescoApiException(int statusCode, String message, String responseBody) {
        super(message);
        this.statusCode = statusCode;
        this.responseBody = responseBody;
    }

    public int statusCode() {
        return statusCode;
    }

    public String responseBody() {
        return responseBody;
    }
}
